"""Generate results/report.md from the analysis outputs (run after harness.analyze).

Every number in the generated sections is computed here from results/*.csv and results/runs/*/run.json.
Hand-written interpretation lives in results/interpretation.md and is spliced in verbatim.
"""
import glob
import json
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
RES = os.path.join(REPO, "results")
EXP = json.load(open(os.path.join(REPO, "bench", "config", "experiment.json")))
STRATS = ["generate_first", "reuse_first", "hybrid", "gui_reuse_first"]
SHORT = {"generate_first": "A gen", "reuse_first": "B reuse", "hybrid": "C hybrid", "gui_reuse_first": "D GUI"}
TIERS = ["S1", "S2", "S3", "S4", "S5"]
MODELS = EXP.get("models", [EXP["model"]])
MTAG = EXP.get("model_tag", {})


def md_table(df, cols, headers=None):
    headers = headers or cols
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join("–" if (isinstance(r[c], float) and np.isnan(r[c])) else str(r[c]) for c in cols) + " |")
    return "\n".join(out)


def pct(x):
    return "–" if x is None or pd.isna(x) else f"{x:.0%}"


def rat(x, lo=None, hi=None, sig=None):
    if x is None or pd.isna(x):
        return "–"
    s = f"{x:.2f}"
    if lo is not None and not pd.isna(lo):
        s += f" [{lo:.2f}–{hi:.2f}]"
    if sig:
        s += " *"
    return f"**{s}**" if x < 1 else s


def main():
    runs = pd.read_csv(os.path.join(RES, "runs.csv"), low_memory=False)
    summ = pd.read_csv(os.path.join(RES, "summary.csv"))
    cx = pd.read_csv(os.path.join(RES, "crossover_analysis.csv"))
    reg = pd.read_csv(os.path.join(RES, "regression.csv"))
    cba = pd.read_csv(os.path.join(RES, "cost_by_action.csv"))
    reff = pd.read_csv(os.path.join(RES, "retrieval_efficiency.csv"))
    rj = {}
    for p in glob.glob(os.path.join(RES, "runs", "*", "run.json")):
        r = json.load(open(p))
        rj[r["run_id"]] = r
    models = [m for m in MODELS if m in set(runs.model)]
    tasks = sorted(runs.task_id.unique(), key=lambda t: runs[runs.task_id == t].task_size_loc.iloc[0])
    L = []
    A = L.append
    A("# Size-dependent retrieval economics across Claude models\n")
    A(f"_Generated by `bench/harness/report.py`. {len(runs)} runs; models {', '.join('`' + m + '`' for m in models)} at effort `{EXP['effort']}`; "
      f"agent harness Claude Code CLI headless. Raw data: `results/`._\n")
    A("### Design\n")
    A("| | |\n|---|---|")
    A(f"| tasks | {', '.join(f'`{t}` ({runs[runs.task_id == t].tier.iloc[0]}, {runs[runs.task_id == t].family.iloc[0]}, ~{runs[runs.task_id == t].task_size_loc.iloc[0]:.0f} LOC)' for t in tasks)} |")
    A(f"| strategies | A generate-first, B reuse-first (API/shell), C hybrid, D reuse-first (GUI browser) |")
    cnt = runs.groupby(["model", "task_id", "strategy"]).size()
    A(f"| trials per cell | min {cnt.min()}, median {int(cnt.median())}, max {cnt.max()} ({len(cnt)} cells) |")
    spend = runs.groupby("model")["inference_cost_usd"].sum()
    A(f"| measured inference spend | " + ", ".join(f"{MTAG.get(m, m)} ${spend.get(m, 0):.2f}" for m in models) + f"; total **${runs.inference_cost_usd.sum():.2f}** |")
    A(f"| agent time | {runs.agent_elapsed_s.sum() / 3600:.1f} h total |\n")
    interp = os.path.join(RES, "interpretation.md")
    if os.path.exists(interp):
        A(open(interp).read().strip() + "\n")

    # ---- 1 telemetry
    A("## 1. Telemetry validation\n")
    rows = []
    for m in models:
        ids = runs[runs.model == m].run_id
        exact = tot = 0
        cdiff = []
        unattr = 0
        for rid in ids:
            r = rj.get(rid)
            if not r:
                continue
            for _, v in (r.get("reconciliation") or {}).items():
                tot += 1
                exact += int(sum(abs(x) for x in v["delta"].values()) == 0)
                unattr += sum(max(0, x) for x in v["delta"].values())
            if r.get("harness_reported_cost_usd") is not None:
                cdiff.append(abs(r["inference_cost_usd"] - r["harness_reported_cost_usd"]))
        rows.append({"model": MTAG.get(m, m), "exact": f"{exact}/{tot}", "unattr": f"{unattr:,}", "maxdiff": f"${max(cdiff):.6f}" if cdiff else "–"})
    A(md_table(pd.DataFrame(rows), ["model", "exact", "unattr", "maxdiff"],
               ["model", "runs whose per-message usage sums exactly to the harness aggregate", "unattributed tokens", "max |computed − harness cost|"]))
    A("\nEvery model invocation is one event in `results/events.jsonl` with provider-reported input, output, cache-read, cache-write (5m/1h) and "
      "thinking tokens. No token count is estimated; estimates are confined to named columns (`screenshot_tokens_estimate`, "
      "`compute_cost_usd_estimate`, `irrelevant_reading_cost_usd_est`).\n")

    # ---- 2 headline regression
    A("## 2. Crossover estimates (regression with task fixed effects)\n")
    A("Model per LLM: `log(cost) ~ task + strategy + strategy × log(task size)` (OLS, HC3 standard errors). For each reuse strategy the fitted "
      "log-ratio to generate-first is `β + γ·(log size − mean)`; the crossover is the size where it reaches 0. 95% CIs from 200 bootstrap "
      "resamples of runs within each task×strategy cell. `γ < 0` means reuse becomes relatively cheaper as tasks grow.\n")
    for metric, label in [("inference_usd", "weighted inference cost (USD)"), ("inference_nocache_usd", "cache-independent cost (all input priced uncached)"), ("tokens", "total tokens incl. cache")]:
        g = reg[reg.metric == metric].copy()
        if g.empty:
            continue
        g["model"] = g["model"].map(lambda m: MTAG.get(m, m))
        g["strategy"] = g["strategy"].map(SHORT)
        g["ratio@mean"] = g.apply(lambda r: f"{r.ratio_at_mean_size:.2f} (p={r.beta_p:.3f})", axis=1)
        g["slope γ"] = g.apply(lambda r: f"{r.gamma_slope:+.2f} [{r.slope_ci_lo:+.2f}, {r.slope_ci_hi:+.2f}] (p={r.gamma_p:.3f})" if not pd.isna(r.get("slope_ci_lo")) else f"{r.gamma_slope:+.2f} (p={r.gamma_p:.3f})", axis=1)
        g["crossover"] = g.apply(lambda r: ("–" if pd.isna(r.crossover_loc) or r.crossover_loc > 1e7 else f"{r.crossover_loc:,.0f}") +
                                 (f" [{r.crossover_ci_lo:,.0f}–{r.crossover_ci_hi:,.0f}]" if not pd.isna(r.get("crossover_ci_lo")) and r.crossover_ci_hi < 1e7 else "") +
                                 ("" if r.crossover_within_observed_range else " (outside observed range)"), axis=1)
        A(f"### {label}\n")
        A(md_table(g.sort_values(["subset", "model", "strategy"]), ["subset", "model", "strategy", "n", "ratio@mean", "slope γ", "crossover"],
                   ["families", "model", "vs A", "runs", "ratio at mean size (p)", "size slope γ [95% CI] (p)", "crossover LOC [95% CI]"]))
        A("")

    # ---- 3 per-cell results
    A("## 3. Results by model, task and strategy\n")
    A("Ratios are mean(strategy)/mean(generate-first) on the same task and model, with bootstrap 95% CI; `*` = Welch test on log cost significant after Holm correction across all cells (α = 0.05). Bold = ratio < 1.\n")
    c = cx[(~cx.quality_adjusted)]
    for m in models:
        A(f"### {MTAG.get(m, m)}\n")
        s = summ[summ.model == m].copy()
        s["tier_rank"] = s["tier"].map(TIERS.index)
        s = s.sort_values(["tier_rank", "task_id", "strategy"])
        out = []
        for _, r in s.iterrows():
            row = {"tier": r.tier, "task": r.task_id, "strat": SHORT[r.strategy], "n": r.n_trials, "pass": pct(r.mean_pass_rate),
                   "succ": f"{r.success_rate:.0%} [{r.success_ci95_lo:.0%}–{r.success_ci95_hi:.0%}]", "loc": f"{r.mean_functional_loc:.0f}",
                   "usd": f"{r.mean_inference_cost_usd:.3f}", "ext": pct(r.mean_retr_external_fraction), "min": f"{r.mean_elapsed_s / 60:.1f}"}
            for met, key in [("inference_usd", "r_usd"), ("tokens", "r_tok"), ("wall_clock_s", "r_time")]:
                q = c[(c.model == m) & (c.task_id == r.task_id) & (c.strategy == r.strategy) & (c.metric == met)]
                row[key] = "" if q.empty else rat(q.ratio.iloc[0], q.ratio_ci95_lo.iloc[0], q.ratio_ci95_hi.iloc[0], bool(q.significant_holm_05.iloc[0]))
            out.append(row)
        A(md_table(pd.DataFrame(out), ["tier", "task", "strat", "n", "pass", "succ", "loc", "usd", "r_usd", "r_tok", "r_time", "ext", "min"],
                   ["tier", "task", "strategy", "n", "pass rate", "success [95% CI]", "func. LOC", "inference $", "$ ratio vs A", "token ratio vs A",
                    "wall-clock ratio vs A", "external code", "elapsed min"]))
        A("")

    # ---- 4 model comparison
    A("## 4. Model comparison\n")
    rows = []
    for m in models:
        for s in STRATS:
            d = runs[(runs.model == m) & (runs.strategy == s)]
            if d.empty:
                continue
            rows.append({"model": MTAG.get(m, m), "strategy": SHORT[s], "runs": len(d), "success": pct(d.success.mean()), "mean $": f"{d.inference_cost_usd.mean():.3f}",
                         "$ per success": f"{d.inference_cost_usd.sum() / max(1, d.success.sum()):.3f}", "mean LOC": f"{d.functional_loc.mean():.0f}",
                         "output tok": f"{d.output_tokens.mean() / 1e3:.1f}k", "cache-read share of input": pct((d.cached_input_tokens / (d.cached_input_tokens + d.input_tokens + d.cache_creation_tokens)).mean()),
                         "acquired code": pct(d.protocol_acquired_any.mean()), "external code": pct(d.retr_external_fraction.mean())})
    A(md_table(pd.DataFrame(rows), list(rows[0].keys())))
    A("\nGeometric-mean inference-cost ratio vs generate-first, by tier:\n")
    g = c[(c.metric == "inference_usd") & c.ratio.notna()].groupby(["model", "strategy", "tier"])["ratio"].apply(lambda x: float(np.exp(np.log(x).mean()))).reset_index()
    pv = g.pivot_table(index=["model", "strategy"], columns="tier", values="ratio").reset_index()
    for t in TIERS:
        if t in pv:
            pv[t] = pv[t].map(lambda x: rat(x))
    pv["model"] = pv["model"].map(lambda m: MTAG.get(m, m))
    pv["strategy"] = pv["strategy"].map(SHORT)
    A(md_table(pv, ["model", "strategy"] + [t for t in TIERS if t in pv]))
    A("")

    # ---- 5 where the money goes
    A("## 5. Where the money goes (cost share by emitted action)\n")
    e = cba[cba.attribution == "emitted_action"].copy()
    e["group"] = e["action_type"].map(lambda a: "retrieval" if a in {"web_search", "github_search", "repository_inspection", "repository_clone", "snippet_retrieval"}
                                      else "copy/integration" if a in {"file_copy", "integration"} else "gui" if a in {"computer_use", "screenshot"}
                                      else "code writing" if a in {"code_generation", "code_edit"} else "testing/debugging" if a in {"test_execution", "debugging"}
                                      else "planning/other")
    pv = e.groupby(["model", "strategy", "tier", "group"])["estimated_cost_usd"].sum().unstack("group").fillna(0)
    pv = pv.div(pv.sum(axis=1), axis=0).reset_index()
    pv["tier_rank"] = pv["tier"].map(TIERS.index)
    pv = pv.sort_values(["model", "strategy", "tier_rank"])
    cols = [x for x in ["retrieval", "gui", "copy/integration", "code writing", "testing/debugging", "planning/other"] if x in pv]
    for col in cols:
        pv[col] = pv[col].map(lambda x: f"{x:.0%}" if x >= 0.005 else "")
    pv["model"] = pv["model"].map(lambda m: MTAG.get(m, m))
    pv["strategy"] = pv["strategy"].map(SHORT)
    A(md_table(pv, ["model", "strategy", "tier"] + cols))
    A("\n_`results/cost_by_action.csv` has the full action breakdown and the consumed-result attribution._\n")

    # ---- 6 retrieval
    A("## 6. Retrieval efficiency\n")
    r = reff[reff.strategy != "generate_first"].copy()
    g = r.groupby(["model", "strategy"]).agg(n=("run_id", "count"), q=("retr_search_queries", "mean"), repos=("retr_repositories_inspected", "mean"),
                                              clones=("retr_repositories_cloned", "mean"), snip=("retr_snippets_retrieved", "mean"),
                                              rloc=("retr_retrieved_loc", "mean"), inc=("retr_retrieved_loc_incorporated", "mean"),
                                              gen=("retr_generated_loc", "mean"), ext=("retr_external_fraction", "mean"), reused=("reused", "mean"),
                                              conv=("retr_search_to_use_conversion", "mean"), fail=("retr_retrieval_failure_rate", "mean"),
                                              share=("retrieval_cost_share", "mean"), irr=("irrelevant_reading_cost_usd_est", "sum"),
                                              rread=("retrieval_reading_cost_usd", "sum")).reset_index()
    g["irr_share"] = g.irr / g.rread.replace(0, np.nan)
    for col in ["q", "repos", "clones", "snip"]:
        g[col] = g[col].map(lambda x: f"{x:.1f}")
    for col in ["rloc", "inc", "gen"]:
        g[col] = g[col].map(lambda x: f"{x:,.0f}")
    for col in ["ext", "reused", "conv", "fail", "share", "irr_share"]:
        g[col] = g[col].map(pct)
    g["model"] = g["model"].map(lambda m: MTAG.get(m, m))
    g["strategy"] = g["strategy"].map(SHORT)
    A(md_table(g, ["model", "strategy", "n", "q", "repos", "clones", "snip", "rloc", "inc", "gen", "ext", "reused", "conv", "fail", "share", "irr_share"],
               ["model", "strategy", "runs", "queries", "repos inspected", "clones", "snippets", "retrieved LOC", "incorporated", "generated LOC",
                "external code", "runs with >20% reuse", "search→use", "retrieval fail", "retrieval cost share", "reading cost on unused material (est.)"]))
    A("\nClone vs snippet acquisition (all reuse runs, inference-cost ratio vs generate-first on the same model and task):\n")
    base = runs[runs.strategy == "generate_first"].groupby(["model", "task_id"]).inference_cost_usd.mean()
    x = runs[runs.strategy.isin(["reuse_first", "gui_reuse_first", "hybrid"])].copy()
    x["ratio"] = [c_ / base.get((m, t), np.nan) for c_, m, t in zip(x.inference_cost_usd, x.model, x.task_id)]
    x["mode"] = np.where(x.retr_repositories_cloned > 0, "clone / package fetch", np.where((x.retr_snippets_retrieved > 0) | (x.gui_copy_operations.fillna(0) > 0), "file / snippet / GUI copy",
                         np.where(x.retr_search_queries > 0, "searched, acquired nothing", "no retrieval")))
    mm = x.groupby("mode").agg(runs=("run_id", "count"), ratio=("ratio", lambda v: float(np.exp(np.log(v.dropna()).mean()))), ext=("retr_external_fraction", "mean"),
                               success=("success", "mean")).reset_index()
    mm["ratio"] = mm["ratio"].map(lambda v: f"{v:.2f}")
    mm["ext"] = mm["ext"].map(pct)
    mm["success"] = mm["success"].map(pct)
    A(md_table(mm, ["mode", "runs", "ratio", "ext", "success"], ["acquisition mode", "runs", "geo-mean $ ratio vs A", "external code", "success"]))
    A("")

    # ---- 7 GUI vs shell
    A("## 7. GUI (browser) retrieval vs API/shell retrieval\n")
    rows = []
    for m in models:
        for t in tasks:
            b = reff[(reff.model == m) & (reff.task_id == t) & (reff.strategy == "reuse_first")]
            d = reff[(reff.model == m) & (reff.task_id == t) & (reff.strategy == "gui_reuse_first")]
            if b.empty or d.empty:
                continue
            rows.append({"model": MTAG.get(m, m), "task": t, "D/B total $": f"{d.inference_cost_usd.mean() / b.inference_cost_usd.mean():.2f}",
                         "D/B retrieval $": f"{d.retrieval_cost_usd.mean() / b.retrieval_cost_usd.mean():.2f}" if b.retrieval_cost_usd.mean() > 0 else "–",
                         "B reused": pct(b.reused.mean()), "D reused": pct(d.reused.mean()), "D screenshots": f"{d.gui_screenshots.mean():.1f}",
                         "D failed nav": f"{d.gui_failed_navigations.mean():.1f}", "D visual-reasoning $": f"{d.gui_visual_reasoning_cost_usd.mean():.3f}"})
    if rows:
        A(md_table(pd.DataFrame(rows), list(rows[0].keys())))
    A("")

    # ---- 8 quality
    A("## 8. Quality, security, licensing, protocol compliance\n")
    rows = []
    for m in models:
        for s in STRATS:
            d = runs[(runs.model == m) & (runs.strategy == s)]
            if d.empty:
                continue
            rows.append({"model": MTAG.get(m, m), "strategy": SHORT[s], "n": len(d), "pass": pct(d.pass_rate.mean()), "succ": pct(d.success.mean()), "strict": pct(d.success_strict.mean()),
                         "sec": f"{d.security_findings.mean():.2f}", "deps": int(d.runtime_dependencies.sum()), "lic": pct(d.license_compliant.astype(float).mean()),
                         "syn": int(d.syntax_errors.sum()), "dup": f"{d.maint_duplicate_line_ratio.mean():.1%}", "comp": pct(d.protocol_compliant.astype(float).mean()),
                         "acq": pct(d.protocol_acquired_any.astype(float).mean()), "deny": int(d.permission_denials.sum()), "contam": int(d.contamination_flags.sum()),
                         "nonsucc": int((d.harness_subtype.astype(str) != "success").sum())})
    A(md_table(pd.DataFrame(rows), list(rows[0].keys()),
               ["model", "strategy", "runs", "pass rate", "success", "100% pass", "security findings/run", "runtime deps", "license-compliant", "syntax errors",
                "dup. lines", "protocol compliant", "acquired code", "permission denials", "contamination flags", "non-success exits"]))
    A("\n_Security findings are pattern-based (eval/Function, exec with interpolation, innerHTML assignment, weak password hashing, Math.random tokens, hard-coded secrets, path traversal)._\n")

    A("## 9. Plots\n")
    for p, cap in [("token_cost_vs_size", "Weighted inference cost vs task size, per model"), ("total_tokens_vs_size", "Total tokens vs task size"),
                   ("output_tokens_vs_size", "Output tokens vs task size"), ("input_tokens_vs_size", "Fresh input tokens vs task size"),
                   ("cached_input_tokens_vs_size", "Cache-read tokens vs task size"), ("model_comparison_ratios", "Cost ratio vs generate-first by model"),
                   ("output_savings_vs_input_overhead", "Output-token savings vs input-token overhead"), ("integration_cost_vs_size", "Integration/copy cost vs retrieved LOC"),
                   ("computer_use_vs_shell", "GUI vs API/shell reuse, per model"), ("success_vs_size", "Hidden-suite pass rate by tier and model")]:
        if os.path.exists(os.path.join(RES, "plots", p + ".png")):
            A(f"![{cap}](plots/{p}.png)\n\n_{cap}._\n")
    A("## 10. Reproduction\n")
    A("```bash\ncd bench\npython3 run_experiment.py --tasks calc-s1,todo-s1,markdown-s1,calc-s2,markdown-s2,kanban-s3,markdown-s3,pm-s4,diagram-s5 \\\n"
      "  --models claude-haiku-5-5,claude-sonnet-5-5,claude-opus-5-5 --trials 5 --parallel 8\npython3 -m harness.analyze && python3 -m harness.report\n```\n")
    open(os.path.join(RES, "report.md"), "w").write("\n".join(L))
    print("wrote results/report.md")


if __name__ == "__main__":
    main()
