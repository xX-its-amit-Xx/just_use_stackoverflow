"""Generate results/report.md from the analysis outputs (run after harness.analyze).

All numbers in the generated sections are computed here from results/*.csv and results/runs/*/run.json.
Hand-written interpretation lives in results/interpretation.md and is spliced in verbatim.
"""
import glob
import json
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
RES = os.path.join(REPO, "results")
EXP = json.load(open(os.path.join(REPO, "bench", "config", "experiment.json")))
STRATS = ["generate_first", "reuse_first", "hybrid", "gui_reuse_first"]
SHORT = {"generate_first": "A gen", "reuse_first": "B reuse", "hybrid": "C hybrid", "gui_reuse_first": "D GUI"}
TIERS = ["S1", "S2", "S3", "S4", "S5"]


def f(x, d=3):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "–"
    if isinstance(x, (int, np.integer)):
        return f"{x:,}"
    if abs(x) >= 1000:
        return f"{x:,.0f}"
    return f"{x:.{d}f}"


def md_table(df, cols, headers=None):
    headers = headers or cols
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(out)


def main():
    runs = pd.read_csv(os.path.join(RES, "runs.csv"))
    summ = pd.read_csv(os.path.join(RES, "summary.csv"))
    cx = pd.read_csv(os.path.join(RES, "crossover_analysis.csv"))
    cba = pd.read_csv(os.path.join(RES, "cost_by_action.csv"))
    reff = pd.read_csv(os.path.join(RES, "retrieval_efficiency.csv"))
    rj = {json.load(open(p))["run_id"]: json.load(open(p)) for p in glob.glob(os.path.join(RES, "runs", "*", "run.json"))}
    runs["tier_rank"] = runs["tier"].map(TIERS.index)
    L = []
    A = L.append
    A("# Size-dependent retrieval economics — pilot report\n")
    A(f"_Generated by `bench/harness/report.py` from {len(runs)} runs. Model `{EXP['model']}` (effort `{EXP['effort']}`) for every strategy; "
      f"agent harness: Claude Code CLI headless (`{runs['run_id'].iloc[0] and json.load(open(glob.glob(os.path.join(RES, 'runs', '*', 'meta.json'))[0]))['claude_code_version']}`)._\n")
    tasks_run = sorted(runs["task_id"].unique(), key=lambda t: (TIERS.index(runs[runs.task_id == t].tier.iloc[0]), t))
    A(f"Tasks executed: {', '.join(f'`{t}` ({runs[runs.task_id == t].tier.iloc[0]})' for t in tasks_run)}. "
      f"Total measured inference spend: **${runs['inference_cost_usd'].sum():.2f}**; agent wall-clock {runs['agent_elapsed_s'].sum() / 3600:.2f} h.\n")
    interp = os.path.join(RES, "interpretation.md")
    if os.path.exists(interp):
        A(open(interp).read().strip() + "\n")

    # ---- telemetry validation
    A("## 1. Telemetry validation\n")
    deltas, cost_diff, unattr = [], [], 0
    for r in rj.values():
        for m, v in (r.get("reconciliation") or {}).items():
            d = v["delta"]
            deltas.append(sum(abs(x) for x in d.values()))
            unattr += sum(max(0, x) for x in d.values())
        if r.get("harness_reported_cost_usd") is not None:
            cost_diff.append(abs(r["inference_cost_usd"] - r["harness_reported_cost_usd"]))
    A(f"- Runs whose per-message transcript usage sums **exactly** to the harness-reported aggregate (all four token classes): "
      f"**{sum(1 for x in deltas if x == 0)}/{len(deltas)}**. Unattributed tokens (harness aggregate minus per-message sum): {unattr:,}.")
    A(f"- Max |computed cost − harness-reported cost| per run: ${max(cost_diff) if cost_diff else float('nan'):.6f} "
      f"(pricing from the live Anthropic pricing page; the harness prices at list).")
    A("- Every model invocation is one event in `results/events.jsonl` with provider-reported `input_tokens`, `output_tokens`, "
      "`cache_read` (as `cached_input_tokens`), `cache_creation` (5m/1h split) and `thinking_tokens` where reported. No token count is estimated; "
      "the only estimates are flagged columns (`screenshot_tokens_estimate`, `compute_cost_usd_estimate`, `irrelevant_reading_cost_usd_est`).\n")

    # ---- main table
    A("## 2. Results by task and strategy\n")
    s = summ.copy()
    s["tier_rank"] = s["tier"].map(TIERS.index)
    s = s.sort_values(["tier_rank", "task_id", "strategy"])
    s["pass"] = s["mean_pass_rate"].map(lambda x: f"{x:.0%}")
    s["succ"] = s.apply(lambda r: f"{r['success_rate']:.0%}", axis=1)
    s["loc"] = s["mean_functional_loc"].map(lambda x: f"{x:.0f}")
    s["usd"] = s.apply(lambda r: f"{r['mean_inference_cost_usd']:.3f}" + (f" [{r['ci95_lo_inference_cost_usd']:.3f}–{r['ci95_hi_inference_cost_usd']:.3f}]" if not pd.isna(r.get("ci95_lo_inference_cost_usd")) else ""), axis=1)
    s["tok"] = s["mean_total_tokens_incl_cache"].map(lambda x: f"{x / 1e3:.0f}k")
    s["out"] = s["mean_output_tokens"].map(lambda x: f"{x / 1e3:.1f}k")
    s["time"] = s["mean_elapsed_s"].map(lambda x: f"{x / 60:.1f}")
    s["ext"] = s["mean_retr_external_fraction"].map(lambda x: f"{x:.0%}")
    s["strat"] = s["strategy"].map(SHORT)
    A(md_table(s, ["tier", "task_id", "strat", "n_trials", "pass", "succ", "loc", "usd", "tok", "out", "time", "ext"],
               ["tier", "task", "strategy", "n", "pass rate", f"success (≥{EXP['success_threshold']:.0%})", "func. LOC", "inference $ mean [95% CI]",
                "tokens (incl. cache)", "output tok", "elapsed min", "external code"]))
    A("\n_Pass rate = hidden-suite tests passed / tests in suite. External code = share of non-trivial final source lines that match retrieved material "
      "(exact or token-skeleton match)._\n")

    # ---- crossover
    A("## 3. Crossover analysis (reuse_cost / generate_cost)\n")
    A("Ratio < 1 ⇒ the reuse strategy is cheaper than generate-first on that task. Quality-adjusted ratios divide each run's cost by its pass rate.\n")
    c = cx[(cx["tier"] != "fit") & cx["ratio"].notna()].copy()
    for q in (False, True):
        sub = c[c["quality_adjusted"] == q]
        if sub.empty:
            continue
        piv = sub.pivot_table(index=["tier", "task_id", "strategy"], columns="metric", values="ratio").reset_index()
        piv["tier_rank"] = piv["tier"].map(TIERS.index)
        piv = piv.sort_values(["tier_rank", "task_id", "strategy"])
        for m in ("tokens", "inference_usd", "execution_usd", "wall_clock_s"):
            if m in piv:
                piv[m] = piv[m].map(lambda x: ("**" + f"{x:.2f}" + "**") if x < 1 else f"{x:.2f}")
        piv["strategy"] = piv["strategy"].map(SHORT)
        A(f"### {'Quality-adjusted' if q else 'Raw'} cost ratios\n")
        A(md_table(piv, ["tier", "task_id", "strategy", "tokens", "inference_usd", "execution_usd", "wall_clock_s"],
                   ["tier", "task", "vs A", "total tokens", "inference $", "execution $", "wall-clock"]))
        A("")
    tier_ratio = c[~c["quality_adjusted"]].groupby(["strategy", "metric", "tier"])["ratio"].apply(lambda x: float(np.exp(np.log(x).mean()))).reset_index()
    tr = tier_ratio.pivot_table(index=["strategy", "metric"], columns="tier", values="ratio").reset_index()
    for t in TIERS:
        if t in tr:
            tr[t] = tr[t].map(lambda x: "–" if pd.isna(x) else (f"**{x:.2f}**" if x < 1 else f"{x:.2f}"))
    tr["strategy"] = tr["strategy"].map(SHORT)
    A("### Geometric-mean ratio per tier (raw)\n")
    A(md_table(tr, ["strategy", "metric"] + [t for t in TIERS if t in tr]))
    fits = cx[cx["tier"] == "fit"]
    if not fits.empty:
        fits = fits[~fits["quality_adjusted"].astype(bool)].copy()
        fits["strategy"] = fits["strategy"].map(SHORT)
        fits["slope"] = fits["fit_slope"].map(lambda x: f"{x:+.2f}")
        fits["crossover"] = fits.apply(lambda r: (f"{r['crossover_loc_estimate']:,.0f} LOC" if not pd.isna(r["crossover_loc_estimate"]) else "–")
                                       + ("" if r["crossover_within_observed_range"] else " (extrapolated)"), axis=1)
        A("\n### Log-log fit of ratio vs functional LOC (pooled across families)\n")
        A("`log10(ratio) = a + b·log10(LOC)`; crossover = LOC where the fitted ratio is 1. With 3 tiers and ≤3 trials this is indicative only.\n")
        A(md_table(fits, ["strategy", "metric", "n_points", "slope", "crossover", "interpretation"]))
    A("")

    # ---- cost by action
    A("## 4. Where the money goes (cost share by action, emitted-action attribution)\n")
    e = cba[cba["attribution"] == "emitted_action"].copy()
    piv = e.pivot_table(index=["strategy", "tier"], columns="action_type", values="cost_share", aggfunc="sum").fillna(0)
    cols = [c for c in ["planning", "web_search", "github_search", "repository_inspection", "repository_clone", "snippet_retrieval", "file_copy",
                        "computer_use", "screenshot", "code_generation", "code_edit", "integration", "test_execution", "debugging", "dependency_installation", "other"] if c in piv]
    piv = piv[cols].reset_index()
    piv["tier_rank"] = piv["tier"].map(TIERS.index)
    piv = piv.sort_values(["strategy", "tier_rank"])
    for col in cols:
        piv[col] = piv[col].map(lambda x: f"{x:.0%}" if x >= 0.005 else "")
    piv["strategy"] = piv["strategy"].map(SHORT)
    A(md_table(piv, ["strategy", "tier"] + cols))
    A("\n_Each invocation is attributed to the tool call it emitted. `results/cost_by_action.csv` also has the consumed-result attribution "
      "(cost assigned to the tool output the call was reading)._\n")

    # ---- retrieval efficiency
    A("## 5. Retrieval efficiency\n")
    r = reff[reff["strategy"] != "generate_first"].copy()
    g = r.groupby(["strategy", "tier"]).agg(
        n=("run_id", "count"), queries=("retr_search_queries", "mean"), results=("retr_search_results_examined", "mean"),
        repos_inspected=("retr_repositories_inspected", "mean"), clones=("retr_repositories_cloned", "mean"),
        files_insp=("retr_files_inspected", "mean"), snippets=("retr_snippets_retrieved", "mean"), retrieved_loc=("retr_retrieved_loc", "mean"),
        incorporated=("retr_retrieved_loc_incorporated", "mean"), modified=("retr_retrieved_loc_modified", "mean"),
        generated=("retr_generated_loc", "mean"), ext=("retr_external_fraction", "mean"), conv=("retr_search_to_use_conversion", "mean"),
        fail=("retr_retrieval_failure_rate", "mean"), retr_share=("retrieval_cost_share", "mean"), irr=("irrelevant_reading_cost_usd_est", "mean"),
        integ=("integration_cost_usd", "mean"), acq=("retr_repository_acquisition_s", "mean")).reset_index()
    g["tier_rank"] = g["tier"].map(TIERS.index)
    g = g.sort_values(["strategy", "tier_rank"])
    g["strategy"] = g["strategy"].map(SHORT)
    for col in ["queries", "results", "repos_inspected", "clones", "files_insp", "snippets"]:
        g[col] = g[col].map(lambda x: f"{x:.1f}")
    for col in ["retrieved_loc", "incorporated", "modified", "generated"]:
        g[col] = g[col].map(lambda x: f"{x:,.0f}")
    for col in ["ext", "conv", "fail", "retr_share"]:
        g[col] = g[col].map(lambda x: "–" if pd.isna(x) else f"{x:.0%}")
    g["irr"] = g["irr"].map(lambda x: f"${x:.3f}")
    g["integ"] = g["integ"].map(lambda x: f"${x:.3f}")
    g["acq"] = g["acq"].map(lambda x: f"{x:.1f}s")
    A(md_table(g, ["strategy", "tier", "n", "queries", "results", "repos_inspected", "clones", "files_insp", "snippets", "retrieved_loc", "incorporated",
                   "modified", "generated", "ext", "conv", "fail", "retr_share", "irr", "integ", "acq"],
               ["strategy", "tier", "n", "queries", "results seen", "repos inspected", "clones", "files inspected", "snippets", "retrieved LOC",
                "incorporated", "modified", "generated LOC", "external %", "search→use", "retrieval fail %", "retrieval cost share",
                "irrelevant reading $ (est.)", "integration $", "acquisition time"]))
    A("")

    # ---- GUI vs shell
    A("## 6. GUI (computer-use) retrieval vs API/shell retrieval\n")
    gcols = [c for c in runs.columns if c.startswith("gui_")]
    gd = runs[runs["strategy"] == "gui_reuse_first"]
    if not gd.empty and gcols:
        gg = gd.groupby("tier")[gcols].mean().reset_index()
        gg["tier_rank"] = gg["tier"].map(TIERS.index)
        gg = gg.sort_values("tier_rank")
        show = ["gui_browser_navigations", "gui_screenshots", "gui_screenshot_tokens_viewed_estimate", "gui_clicks", "gui_text_selections",
                "gui_copy_operations", "gui_paste_operations", "gui_failed_navigations", "gui_gui_action_time_s", "gui_visual_reasoning_calls",
                "gui_visual_reasoning_cost_usd"]
        show = [x for x in show if x in gg]
        for col in show:
            gg[col] = gg[col].map(lambda x: f"{x:.2f}" if "usd" in col else f"{x:.1f}")
        A(md_table(gg, ["tier"] + show, ["tier"] + [x.replace("gui_", "") for x in show]))
    A("")
    pair = []
    for t in tasks_run:
        b = runs[(runs.task_id == t) & (runs.strategy == "reuse_first")]
        d = runs[(runs.task_id == t) & (runs.strategy == "gui_reuse_first")]
        if len(b) and len(d):
            rb = reff[(reff.task_id == t) & (reff.strategy == "reuse_first")]["retrieval_cost_usd"].mean()
            rd = reff[(reff.task_id == t) & (reff.strategy == "gui_reuse_first")]["retrieval_cost_usd"].mean()
            pair.append({"task": t, "tier": b.tier.iloc[0], "B $": f"{b.inference_cost_usd.mean():.3f}", "D $": f"{d.inference_cost_usd.mean():.3f}",
                         "D/B total": f"{d.inference_cost_usd.mean() / b.inference_cost_usd.mean():.2f}",
                         "B retrieval $": f"{rb:.3f}", "D retrieval $": f"{rd:.3f}", "D/B retrieval": f"{rd / rb:.2f}" if rb > 0 else "–",
                         "B ext %": f"{b.retr_external_fraction.mean():.0%}", "D ext %": f"{d.retr_external_fraction.mean():.0%}",
                         "B min": f"{b.elapsed_s.mean() / 60:.1f}", "D min": f"{d.elapsed_s.mean() / 60:.1f}"})
    if pair:
        pdf = pd.DataFrame(pair)
        A(md_table(pdf, list(pdf.columns)))
    A("")

    # ---- quality
    A("## 7. Quality, security, licensing, protocol compliance\n")
    qq = runs.groupby("strategy").agg(n=("run_id", "count"), pass_rate=("pass_rate", "mean"), success=("success", "mean"),
                                      strict=("success_strict", "mean"), sec=("security_findings", "mean"), deps=("runtime_dependencies", "sum"),
                                      lic=("license_compliant", "mean"), syn=("syntax_errors", "sum"), contam=("contamination_flags", "sum"),
                                      comp=("protocol_compliant", "mean"), comp_strict=("protocol_compliant_strict", "mean"),
                                      acquired=("protocol_acquired_any", "mean"), dup=("maint_duplicate_line_ratio", "mean"),
                                      lpf=("maint_loc_per_function", "mean"), human=("human_interventions", "sum"),
                                      budget_stop=("harness_subtype", lambda x: int((x.astype(str) != "success").sum()))).reindex(STRATS).dropna(how="all").reset_index()
    for col in ["pass_rate", "success", "strict", "lic", "comp", "comp_strict", "acquired"]:
        qq[col] = qq[col].map(lambda x: f"{x:.0%}")
    qq["sec"] = qq["sec"].map(lambda x: f"{x:.2f}")
    qq["dup"] = qq["dup"].map(lambda x: f"{x:.1%}")
    qq["lpf"] = qq["lpf"].map(lambda x: f"{x:.1f}")
    qq["strategy"] = qq["strategy"].map(SHORT)
    A(md_table(qq, ["strategy", "n", "pass_rate", "success", "strict", "sec", "deps", "lic", "syn", "dup", "lpf", "comp", "acquired", "contam", "human", "budget_stop"],
               ["strategy", "n", "pass rate", "success", "100% pass", "security findings/run", "runtime deps", "license-compliant runs",
                "syntax errors", "dup. lines", "LOC/function", "protocol compliant", "acquired code", "contamination flags", "human interventions",
                "non-success exits"]))
    A("\n_Security findings are pattern-based (eval/Function, exec with interpolation, innerHTML assignment, weak password hashing, Math.random tokens, "
      "hard-coded secrets, path traversal). Dependency vulnerabilities: `npm audit` runs only when dependencies are declared (none were allowed)._\n")
    issues = [(rid, i) for rid, r in rj.items() for i in r["quality"]["license"]["issues"]]
    if issues:
        A("License issues found:\n")
        for rid, i in issues[:20]:
            A(f"- `{rid}`: {i}")
        A("")

    A("## 8. Plots\n")
    for p, cap in [("token_cost_vs_size", "Weighted inference cost and total tokens vs functional LOC (log-log; lines join tier means)"),
                   ("output_tokens_vs_size", "Output tokens vs functional LOC"), ("input_tokens_vs_size", "Fresh vs cache-read input tokens vs LOC"),
                   ("output_savings_vs_input_overhead", "Output-token savings vs input-token overhead relative to generate-first"),
                   ("integration_cost_vs_size", "Integration/copy cost vs retrieved LOC"), ("computer_use_vs_shell", "GUI vs API/shell reuse"),
                   ("success_vs_size", "Hidden-suite pass rate by tier")]:
        A(f"![{cap}](plots/{p}.png)\n\n_{cap}._\n")

    A("## 9. Reproduction\n")
    A("```bash\ncd bench\npython3 run_experiment.py --tasks calc-s1,todo-s1,calc-s2,markdown-s2,kanban-s3 --trials 3 --parallel 6\n"
      "python3 -m harness.analyze && python3 -m harness.report\n```\n")
    A("Re-evaluate a stored run without re-running the agent: `python3 -m harness.evaluate results/runs/<run_id> --no-copy` "
      "(requires the run's workspace to still exist for provenance matching; artifacts in `results/artifacts/` are sufficient for the test suites).\n")
    open(os.path.join(RES, "report.md"), "w").write("\n".join(L))
    print("wrote results/report.md")


if __name__ == "__main__":
    main()
