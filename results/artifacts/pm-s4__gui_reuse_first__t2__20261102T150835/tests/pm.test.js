import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from '../src/server.js';
test('flow: workflow, blocks, search, sprint, csv', async () => {
  let t = new Date('2025-01-01T10:00:00Z');
  const srv = createServer({ clock: () => t }); await new Promise((r) => srv.listen(0, r)); const base = `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, tk) => { const r = await fetch(base + p, { method: m, headers: { 'content-type': 'application/json', ...(tk ? { authorization: `Bearer ${tk}` } : {}) }, body: b === undefined ? undefined : typeof b === 'string' ? b : JSON.stringify(b) }); const x = await r.text(); let j = null; try { j = JSON.parse(x); } catch { j = x; } return { status: r.status, body: j }; };
  for (const u of ['alice', 'bob']) await call('POST', '/api/auth/register', { username: u, password: 'password123' });
  const A = (await call('POST', '/api/auth/login', { username: 'alice', password: 'password123' })).body.token;
  const B = (await call('POST', '/api/auth/login', { username: 'bob', password: 'password123' })).body.token;
  const ws = (await call('POST', '/api/workspaces', { name: 'A', key: 'ACME' }, A)).body;
  await call('POST', `/api/workspaces/${ws.id}/members`, { username: 'bob', role: 'member' }, A);
  const pr = (await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'W', key: 'WEB' }, A)).body;
  const sp = (await call('POST', `/api/projects/${pr.id}/sprints`, { name: 'S1' }, A)).body;
  const i1 = (await call('POST', `/api/projects/${pr.id}/issues`, { type: 'bug', title: 'Crash', storyPoints: 5, sprintId: sp.id, labels: ['x'] }, A)).body;
  const i2 = (await call('POST', `/api/projects/${pr.id}/issues`, { type: 'task', title: 'Fix it', storyPoints: 3, sprintId: sp.id }, A)).body;
  assert.equal(i1.status, 'Todo');
  assert.equal((await call('POST', `/api/issues/${i1.key}/links`, { type: 'blocks', target: i2.key }, A)).status, 201);
  assert.equal((await call('GET', `/api/issues/${i2.key}`, undefined, A)).body.links[0].type, 'blocked_by');
  assert.equal((await call('PATCH', `/api/issues/${i2.key}`, { status: 'Done' }, A)).body.error, 'blocked');
  await call('POST', `/api/sprints/${sp.id}/start`, undefined, A);
  t = new Date('2025-01-02T10:00:00Z');
  assert.equal((await call('PATCH', `/api/issues/${i1.key}`, { status: 'Done', assigneeId: undefined }, A)).body.resolvedAt != null, true);
  const rep = (await call('GET', `/api/sprints/${sp.id}/report`, undefined, A)).body;
  assert.deepEqual(rep.burndown.map((b) => b.remainingPoints), [8, 3]); assert.equal(rep.completedPoints, 5);
  const s = await call('GET', '/api/search?q=' + encodeURIComponent('type:bug -label:wontfix "crash" is:resolved'), undefined, B);
  assert.equal(s.body.length, 1);
  assert.equal((await call('GET', '/api/search?q=status:"', undefined, A)).status, 400);
  const csv = (await call('GET', `/api/projects/${pr.id}/export.csv`, undefined, A)).body;
  assert.ok(csv.startsWith('key,type,title'));
  const imp = await call('POST', `/api/projects/${pr.id}/import.csv`, 'type,title,status\ntask,"a, b",Todo\nbogus,x,Todo\n', A);
  assert.equal(imp.body.created, 1); assert.equal(imp.body.errors.length, 1);
  await call('POST', `/api/issues/${i1.key}/comments`, { body: 'hi @bob' }, A);
  assert.equal((await call('GET', '/api/notifications?unread=true', undefined, B)).body.length >= 1, true);
  srv.close();
});
