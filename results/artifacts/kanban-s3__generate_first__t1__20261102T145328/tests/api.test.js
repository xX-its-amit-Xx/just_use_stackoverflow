import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createServer } from '../src/server.js';

test('flow, wip, move, persistence', async () => {
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'k-')), 'd.json');
  let srv = createServer({ dataFile: file }); await new Promise(r => srv.listen(0, r));
  const base = () => `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, t) => { const r = await fetch(base() + p, { method: m, headers: { 'content-type': 'application/json', ...(t ? { authorization: 'Bearer ' + t } : {}) }, body: b ? JSON.stringify(b) : undefined }); return { s: r.status, j: r.status === 204 ? null : await r.json() }; };
  await call('POST', '/api/auth/register', { username: 'Alice', password: 'password1' });
  await call('POST', '/api/auth/register', { username: 'bob', password: 'password1' });
  const t = (await call('POST', '/api/auth/login', { username: 'alice', password: 'password1' })).j.token;
  const tb = (await call('POST', '/api/auth/login', { username: 'bob', password: 'password1' })).j.token;
  const b = (await call('POST', '/api/boards', { name: 'B' }, t)).j; 
  assert.equal((await call('GET', '/api/boards/' + b.id, null, tb)).s, 403);
  const g = (await call('GET', '/api/boards/' + b.id, null, t)).j;
  const [c1, c2] = g.columns;
  await call('PATCH', '/api/columns/' + c2.id, { wipLimit: 1 }, t);
  const k1 = (await call('POST', `/api/columns/${c1.id}/cards`, { title: 'a' }, t)).j;
  const k2 = (await call('POST', `/api/columns/${c1.id}/cards`, { title: 'b', position: 0 }, t)).j;
  assert.equal((await call('POST', `/api/cards/${k1.id}/move`, { columnId: c2.id }, t)).s, 200);
  const r = await call('POST', `/api/cards/${k2.id}/move`, { columnId: c2.id }, t);
  assert.equal(r.s, 409); assert.equal(r.j.error, 'wip_limit');
  assert.equal((await call('POST', `/api/boards/${b.id}/members`, { username: 'bob', role: 'viewer' }, t)).s, 201);
  assert.equal((await call('POST', `/api/cards/${k1.id}/comments`, { body: 'x' }, tb)).s, 403);
  const act = (await call('GET', `/api/boards/${b.id}/activity`, null, t)).j;
  assert.equal(act[0].type, 'member.added');
  for (let i = 0; i < 5; i++) await call('POST', '/api/auth/login', { username: 'bob', password: 'nope' });
  assert.equal((await call('POST', '/api/auth/login', { username: 'bob', password: 'password1' })).s, 429);
  srv.close();
  srv = createServer({ dataFile: file }); await new Promise(r => srv.listen(0, r));
  const t2 = (await call('POST', '/api/auth/login', { username: 'alice', password: 'password1' })).j.token;
  assert.equal((await call('GET', '/api/boards', null, t2)).j.length, 1);
  assert.ok(!fs.readFileSync(file, 'utf8').includes('password1'));
  assert.equal((await fetch(base() + '/')).headers.get('content-type').startsWith('text/html'), true);
  srv.close();
});
