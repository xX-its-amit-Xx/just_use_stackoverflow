import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from '../src/server.js';
test('flow', async () => {
  let t = new Date('2025-01-01T10:00:00Z');
  const srv = createServer({ clock: () => t }); await new Promise(r => srv.listen(0, r)); const base = `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, tk, raw) => { const r = await fetch(base + p, { method: m, headers: { 'content-type': raw ? 'text/csv' : 'application/json', ...(tk ? { authorization: `Bearer ${tk}` } : {}) }, body: raw ? b : b && JSON.stringify(b) }); const tx = await r.text(); let body = tx; try { body = JSON.parse(tx); } catch {} return { status: r.status, body }; };
  await call('POST', '/api/auth/register', { username: 'alice', password: 'password123' });
  await call('POST', '/api/auth/register', { username: 'bob', password: 'password123' });
  const A = (await call('POST', '/api/auth/login', { username: 'alice', password: 'password123' })).body.token;
  const ws = (await call('POST', '/api/workspaces', { name: 'Acme', key: 'ACME' }, A)).body;
  await call('POST', `/api/workspaces/${ws.id}/members`, { username: 'bob', role: 'member' }, A);
  const pr = (await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'Web', key: 'WEB' }, A)).body;
  const i1 = (await call('POST', `/api/projects/${pr.id}/issues`, { type: 'task', title: 'one', storyPoints: 5, labels: ['x'] }, A)).body;
  const i2 = (await call('POST', `/api/projects/${pr.id}/issues`, { type: 'task', title: 'two' }, A)).body;
  assert.equal(i1.status, 'Todo');
  await call('POST', `/api/issues/${i1.key}/links`, { type: 'blocks', target: i2.key }, A);
  assert.equal((await call('PATCH', `/api/issues/${i2.key}`, { status: 'Done' }, A)).body.error, 'blocked');
  const sp = (await call('POST', `/api/projects/${pr.id}/sprints`, { name: 'S1' }, A)).body;
  await call('PATCH', `/api/issues/${i1.key}`, { sprintId: sp.id }, A);
  await call('POST', `/api/sprints/${sp.id}/start`, {}, A);
  t = new Date('2025-01-02T10:00:00Z');
  await call('PATCH', `/api/issues/${i1.key}`, { status: 'Done' }, A);
  const rep = (await call('GET', `/api/sprints/${sp.id}/report`, undefined, A)).body;
  assert.equal(rep.completedPoints, 5); assert.deepEqual(rep.burndown.map(b => b.remainingPoints), [5, 0]);
  assert.equal((await call('PATCH', `/api/issues/${i2.key}`, { status: 'Done' }, A)).status, 200);
  const s = await call('GET', '/api/search?q=' + encodeURIComponent('label:x -status:Todo "one"'), undefined, A);
  assert.equal(s.body.length, 1);
  assert.equal((await call('GET', '/api/search?q=' + encodeURIComponent('foo:bar'), undefined, A)).status, 400);
  const csv = (await call('GET', `/api/projects/${pr.id}/export.csv`, undefined, A)).body;
  assert.match(csv, /^key,type,title/);
  const imp = await call('POST', `/api/projects/${pr.id}/import.csv`, 'type,title,status\ntask,"a, b",Todo\nbug,,Todo\n', A, true);
  assert.equal(imp.body.created, 1); assert.equal(imp.body.errors[0].line, 3);
  const B = (await call('POST', '/api/auth/login', { username: 'bob', password: 'password123' })).body.token;
  await call('POST', `/api/issues/${i1.key}/comments`, { body: 'hi @bob' }, A);
  assert.equal((await call('GET', '/api/notifications?unread=true', undefined, B)).body.length, 1);
  assert.equal((await call('GET', `/api/workspaces/${ws.id}/audit`, undefined, A)).status, 200);
  srv.close();
});
