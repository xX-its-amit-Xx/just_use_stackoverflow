import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from '../src/server.js';
test('flows', async () => {
  let t = new Date('2026-01-01T10:00:00Z');
  const srv = createServer({ clock: () => t }); await new Promise(r => srv.listen(0, r));
  const base = `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, tk, raw) => { const r = await fetch(base + p, { method: m, headers: { ...(raw ? { 'content-type': 'text/csv' } : { 'content-type': 'application/json' }), ...(tk ? { authorization: `Bearer ${tk}` } : {}) }, body: raw ?? (b && JSON.stringify(b)) }); const x = await r.text(); let body; try { body = JSON.parse(x); } catch { body = x; } return { status: r.status, body }; };
  await call('POST', '/api/auth/register', { username: 'alice', password: 'password123' });
  await call('POST', '/api/auth/register', { username: 'bob', password: 'password123' });
  const tk = (await call('POST', '/api/auth/login', { username: 'alice', password: 'password123' })).body.token;
  const ws = (await call('POST', '/api/workspaces', { name: 'A', key: 'ACME' }, tk)).body;
  const pr = (await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'W', key: 'WEB' }, tk)).body;
  const mk = b => call('POST', `/api/projects/${pr.id}/issues`, b, tk);
  const a = (await mk({ title: 'A', type: 'bug', storyPoints: 5, labels: ['x'] })).body;
  const b = (await mk({ title: 'B', storyPoints: 3 })).body;
  assert.equal((await call('POST', `/api/issues/${a.key}/links`, { type: 'blocks', target: b.key }, tk)).status, 201);
  assert.equal((await call('PATCH', `/api/issues/${b.key}`, { status: 'Done' }, tk)).body.error, 'blocked');
  assert.equal((await call('PATCH', `/api/issues/${a.key}`, { status: 'Done' }, tk)).body.resolvedAt != null, true);
  assert.equal((await call('PATCH', `/api/issues/${b.key}`, { status: 'Done' }, tk)).status, 200);
  const s = await call('GET', '/api/search?q=' + encodeURIComponent('type:bug -label:y is:resolved'), null, tk);
  assert.equal(s.body.length, 1);
  assert.equal((await call('GET', '/api/search?q=status:%22x', null, tk)).status, 400);
  const csv = (await call('GET', `/api/projects/${pr.id}/export.csv`, null, tk)).body;
  assert.ok(csv.startsWith('key,type,title'));
  const imp = await call('POST', `/api/projects/${pr.id}/import.csv`, null, tk, 'key,type,title,status\n,task,"Hi, there",Todo\n,task,,Todo\n');
  assert.equal(imp.body.created, 1); assert.equal(imp.body.errors[0].line, 3);
  const sp = (await call('POST', `/api/projects/${pr.id}/sprints`, { name: 'S1', startDate: '2026-01-01', endDate: '2026-01-05' }, tk)).body;
  await call('PATCH', `/api/issues/WEB-3`, { sprintId: sp.id, storyPoints: 4 }, tk);
  await call('POST', `/api/sprints/${sp.id}/start`, null, tk);
  t = new Date('2026-01-03T10:00:00Z');
  const rep = (await call('GET', `/api/sprints/${sp.id}/report`, null, tk)).body;
  assert.equal(rep.burndown.length, 3); assert.equal(rep.committedPoints, 4);
  srv.close();
});
