import { test } from 'node:test';
import assert from 'node:assert/strict';
import { render } from '../../src/markdown.js';
const n = s => s.replace(/\s*(<\/?(?:p|h[1-6]|ul|ol|li|blockquote|pre|hr)\b[^>]*>)\s*/g, '$1').trim();
const cases = [
  ['## H2 ##', '<h2>H2</h2>'],
  ['###### six', '<h6>six</h6>'],
  ['####### seven', '<p>####### seven</p>'],
  ['#nospace', '<p>#nospace</p>'],
  ['a\nb\n\nc', '<p>a\nb</p><p>c</p>'],
  ['**s** and __t__ and _u_', '<p><strong>s</strong> and <strong>t</strong> and <em>u</em></p>'],
  ['snake_case_word', '<p>snake_case_word</p>'],
  ['***both***', '<p><em><strong>both</strong></em></p>'],
  ['*a **b** c*', '<p><em>a <strong>b</strong> c</em></p>'],
  ['`a<b>&`', '<p><code>a&lt;b&gt;&amp;</code></p>'],
  ['`` a`b ``', '<p><code>a`b</code></p>'],
  ['[t](http://x.com "T")', '<p><a href="http://x.com" title="T">t</a></p>'],
  ['[t](/u)', '<p><a href="/u">t</a></p>'],
  ['![alt *x*](i.png)', '<p><img src="i.png" alt="alt x" /></p>'],
  ['[a *b*](u)', '<p><a href="u">a <em>b</em></a></p>'],
  ['- a\n- b', '<ul><li>a</li><li>b</li></ul>'],
  ['* a\n* b', '<ul><li>a</li><li>b</li></ul>'],
  ['1. a\n2. b', '<ol><li>a</li><li>b</li></ol>'],
  ['3. a\n4. b', '<ol start="3"><li>a</li><li>b</li></ol>'],
  ['```js\nx < 1 && *y*\n```', '<pre><code class="language-js">x &lt; 1 &amp;&amp; *y*\n</code></pre>'],
  ['```\nplain\n```', '<pre><code>plain\n</code></pre>'],
  ['> quote *x*\n> more', '<blockquote><p>quote <em>x</em>\nmore</p></blockquote>'],
  ['> a\nlazy', '<blockquote><p>a\nlazy</p></blockquote>'],
  ['a\n\n---\n\nb', '<p>a</p><hr /><p>b</p>'],
  ['---', '<hr />'],
  ['<div>"hi" & bye</div>', '<p>&lt;div&gt;&quot;hi&quot; &amp; bye&lt;/div&gt;</p>'],
  ['a <b>bold</b>', '<p>a &lt;b&gt;bold&lt;/b&gt;</p>'],
  ['para\n- item', '<p>para</p><ul><li>item</li></ul>'],
  ['- a\n\n- b', '<ul><li><p>a</p></li><li><p>b</p></li></ul>'],
  ['\\*not em\\*', '<p>*not em*</p>'],
  ['*a', '<p>*a</p>'],
  ['[nolink]', '<p>[nolink]</p>'],
  ['[a](<b c>)', '<p><a href="b%20c">a</a></p>'],
  ['a  \nb', '<p>a<br />\nb</p>'],
  ['# Title\ntext', '<h1>Title</h1><p>text</p>'],
  ['- a\n- b\n\npara', '<ul><li>a</li><li>b</li></ul><p>para</p>'],
  ['1. a\n- b', '<ol><li>a</li></ol><ul><li>b</li></ul>'],
  ['*foo*bar', '<p><em>foo</em>bar</p>'],
  ['_foo_bar', '<p>_foo_bar</p>'],
  ['**foo*', '<p>*<em>foo</em></p>'],
  ['[link [x](y)](z)', '<p>[link <a href="y">x</a>](z)</p>'],
  ['a & b "q"', '<p>a &amp; b &quot;q&quot;</p>'],
  ['```\nunclosed', '<pre><code>unclosed\n</code></pre>'],
  ['', ''],
];
for (const [md, html] of cases) test(JSON.stringify(md), () => assert.equal(n(render(md)), html));
const more = [
  ['- a\nlazy\n- b', '<ul><li>a\nlazy</li><li>b</li></ul>'],
  ['> a\n- b', '<blockquote><p>a</p></blockquote><ul><li>b</li></ul>'],
  ['- a\n\n  b', '<ul><li><p>a</p><p>b</p></li></ul>'],
  ['- ```\n  code\n  ```', '<ul><li><pre><code>code\n</code></pre></li></ul>'],
  ['Foo\n---', '<h2>Foo</h2>'],
  ['* * *', '<hr />'],
  ['[a](http://x.com/a b)', '<p>[a](http://x.com/a b)</p>'],
  ['[ä](/ü)', '<p><a href="/%C3%BC">ä</a></p>'],
  ['&copy; &#35; &bogus;', '<p>© # &amp;bogus;</p>'],
];
for (const [md, html] of more) test(JSON.stringify(md), () => assert.equal(n(render(md)), html));
