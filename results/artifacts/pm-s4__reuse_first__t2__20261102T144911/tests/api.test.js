import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from '../src/server.js';
test('flow: workflow, blocks, search, csv, sprint', async () => {
  let now = new Date('2024-01-01T10:00:00Z');
  const srv = createServer({ clock: () => now }); await new Promise(r => srv.listen(0, r)); const base = `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, t, raw) => { const r = await fetch(base + p, { method: m, headers: { ...(raw ? { 'content-type': 'text/csv' } : { 'content-type': 'application/json' }), ...(t ? { authorization: `Bearer ${t}` } : {}) }, body: b && (raw ? b : JSON.stringify(b)) }); const x = await r.text(); let body = x; try { body = JSON.parse(x); } catch {} return { status: r.status, body }; };
  await call('POST', '/api/auth/register', { username: 'alice', password: 'password123' });
  const t = (await call('POST', '/api/auth/login', { username: 'alice', password: 'password123' })).body.token;
  const ws = (await call('POST', '/api/workspaces', { name: 'A', key: 'ACME' }, t)).body;
  const pr = (await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'W', key: 'WEB' }, t)).body;
  const sp = (await call('POST', `/api/projects/${pr.id}/sprints`, { name: 'S1', endDate: '2024-01-05' }, t)).body;
  const a = (await call('POST', `/api/projects/${pr.id}/issues`, { title: 'a', type: 'bug', storyPoints: 3, sprintId: sp.id, priority: 'high' }, t)).body;
  const b = (await call('POST', `/api/projects/${pr.id}/issues`, { title: 'b', storyPoints: 2, sprintId: sp.id }, t)).body;
  assert.equal((await call('POST', `/api/issues/${a.key}/links`, { type: 'blocks', target: b.key }, t)).status, 201);
  assert.equal((await call('GET', `/api/issues/${b.key}`, null, t)).body.links[0].type, 'blocked_by');
  await call('POST', `/api/sprints/${sp.id}/start`, {}, t);
  assert.equal((await call('PATCH', `/api/issues/${b.key}`, { status: 'Done' }, t)).body.error, 'blocked');
  now = new Date('2024-01-02T10:00:00Z');
  assert.equal((await call('PATCH', `/api/issues/${a.key}`, { status: 'Done' }, t)).body.resolvedAt, now.toISOString());
  now = new Date('2024-01-03T10:00:00Z');
  const rep = (await call('GET', `/api/sprints/${sp.id}/report`, null, t)).body;
  assert.deepEqual(rep.burndown.map(x => x.remainingPoints), [5, 2, 2]);
  assert.equal(rep.committedPoints, 5);
  const s = await call('GET', '/api/search?q=' + encodeURIComponent('type:bug -label:x is:resolved'), null, t);
  assert.equal(s.body.length, 1);
  assert.equal((await call('GET', '/api/search?q=status:', null, t)).status, 400);
  const csv = (await call('GET', `/api/projects/${pr.id}/export.csv`, null, t)).body;
  assert.ok(csv.startsWith('key,type,title'));
  const imp = await call('POST', `/api/projects/${pr.id}/import.csv`, 'key,type,title,priority\n,task,"x, y",low\n,bogus,z,low\n', t, true);
  assert.equal(imp.body.created, 1); assert.equal(imp.body.errors[0].line, 3);
  const n = await call('GET', '/api/notifications', null, t); assert.equal(n.status, 200);
  srv.close();
});
