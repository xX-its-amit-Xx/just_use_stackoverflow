import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createServer } from '../src/server.js';
test('flow', async () => {
  const f = (await import('node:os')).tmpdir() + '/k' + Date.now() + '.json';
  let srv = createServer({ dataFile: f }); await new Promise(r => srv.listen(0, r));
  const base = () => `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, t) => { const r = await fetch(base() + p, { method: m, headers: { 'content-type': 'application/json', ...(t ? { authorization: 'Bearer ' + t } : {}) }, body: b ? JSON.stringify(b) : undefined }); return [r.status, r.status === 204 ? null : await r.json()]; };
  await call('POST', '/api/auth/register', { username: 'Al', password: 'password123' });
  assert.equal((await call('POST', '/api/auth/register', { username: 'al_', password: 'password123' }))[0], 201);
  const [, { token }] = await call('POST', '/api/auth/login', { username: 'al_', password: 'password123' });
  const [, b] = await call('POST', '/api/boards', { name: 'B' }, token);
  const [c1, c2] = b.columns.length ? b.columns : [];
  const [, bb] = await call('GET', '/api/boards/' + b.id, null, token);
  const cols = bb.columns;
  await call('PATCH', '/api/columns/' + cols[1].id, { wipLimit: 1 }, token);
  const [s, card] = await call('POST', `/api/columns/${cols[0].id}/cards`, { title: 'x' }, token);
  assert.equal(s, 201);
  assert.equal((await call('POST', `/api/cards/${card.id}/move`, { columnId: cols[1].id }, token))[0], 200);
  const [, c2b] = await call('POST', `/api/columns/${cols[0].id}/cards`, { title: 'y' }, token);
  assert.equal((await call('POST', `/api/cards/${c2b.id}/move`, { columnId: cols[1].id }, token))[1].error, 'wip_limit');
  srv.close(); srv = createServer({ dataFile: f }); await new Promise(r => srv.listen(0, r));
  const [, t2] = await call('POST', '/api/auth/login', { username: 'al_', password: 'password123' });
  assert.equal((await call('GET', '/api/boards/' + b.id + '/activity', null, t2.token))[1].length >= 5, true);
  assert.ok(!fs.readFileSync(f, 'utf8').includes('password123'));
  for (let i = 0; i < 5; i++) await call('POST', '/api/auth/login', { username: 'zz', password: 'bad' });
  assert.equal((await call('POST', '/api/auth/login', { username: 'zz', password: 'bad' }))[0], 429);
  srv.close();
});
