import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from '../../src/server.js';
test('flow: workflow, search, csv, sprint, notifications', async () => {
  let t = new Date('2026-01-01T10:00:00Z');
  const srv = createServer({ clock: () => t }); await new Promise(r => srv.listen(0, r)); const base = `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, tk, raw) => { const r = await fetch(base + p, { method: m, headers: { ...(raw ? { 'content-type': 'text/csv' } : { 'content-type': 'application/json' }), ...(tk ? { authorization: `Bearer ${tk}` } : {}) }, body: raw ? b : b && JSON.stringify(b) }); const x = await r.text(); let j = null; try { j = JSON.parse(x); } catch { j = x; } return { status: r.status, body: j }; };
  await call('POST', '/api/auth/register', { username: 'alice', password: 'password123' });
  await call('POST', '/api/auth/register', { username: 'bob', password: 'password123' });
  const a = (await call('POST', '/api/auth/login', { username: 'alice', password: 'password123' })).body;
  const b = (await call('POST', '/api/auth/login', { username: 'bob', password: 'password123' })).body;
  const ws = (await call('POST', '/api/workspaces', { name: 'Acme', key: 'ACME' }, a.token)).body;
  await call('POST', `/api/workspaces/${ws.id}/members`, { username: 'bob', role: 'member' }, a.token);
  const pr = (await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'Web', key: 'WEB' }, a.token)).body;
  const i1 = (await call('POST', `/api/projects/${pr.id}/issues`, { title: 'One, "q"', type: 'bug', storyPoints: 3, assigneeId: b.user.id }, a.token)).body;
  const i2 = (await call('POST', `/api/projects/${pr.id}/issues`, { title: 'Two', storyPoints: 2 }, a.token)).body;
  assert.equal(i1.status, 'Todo');
  assert.equal((await call('POST', `/api/issues/${i2.key}/links`, { type: 'blocks', target: i1.key }, a.token)).status, 201);
  assert.equal((await call('PATCH', `/api/issues/${i1.key}`, { status: 'Done' }, a.token)).body.error, 'blocked');
  const n = (await call('GET', '/api/notifications?unread=true', null, b.token)).body; assert.equal(n.length, 1);
  const s = (await call('POST', `/api/projects/${pr.id}/sprints`, { name: 'S1' }, a.token)).body;
  await call('PATCH', `/api/issues/${i2.key}`, { sprintId: s.id }, a.token);
  await call('POST', `/api/sprints/${s.id}/start`, null, a.token);
  t = new Date('2026-01-02T10:00:00Z');
  await call('PATCH', `/api/issues/${i2.key}`, { status: 'Done' }, a.token);
  const rep = (await call('GET', `/api/sprints/${s.id}/report`, null, a.token)).body;
  assert.equal(rep.completedPoints, 2); assert.equal(rep.burndown.length, 2); assert.equal(rep.burndown[1].remainingPoints, 0);
  assert.equal((await call('GET', '/api/search?q=type:bug%20-label:x', null, a.token)).body.total, 1);
  assert.equal((await call('GET', '/api/search?q=status:%22Done', null, a.token)).status, 400);
  const csv = (await call('GET', `/api/projects/${pr.id}/export.csv`, null, a.token)).body;
  assert.ok(csv.startsWith('key,type,title'));
  const imp = (await call('POST', `/api/projects/${pr.id}/import.csv`, csv + 'x,bug,,Todo\r\n', a.token, true)).body;
  assert.equal(imp.created, 2); assert.equal(imp.errors.length, 1);
  assert.equal((await call('GET', '/')).status, 200);
  srv.close();
});
