import { test } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { createServer } from '../src/server.js';
test('features', async () => {
  let t0 = new Date('2026-01-01T10:00:00Z');
  const srv = createServer({ clock: () => t0 }); await new Promise(r => srv.listen(0, r)); const base = `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, t, raw) => { const r = await fetch(base + p, { method: m, headers: { ...(raw ? { 'content-type': 'text/csv' } : { 'content-type': 'application/json' }), ...(t ? { authorization: `Bearer ${t}` } : {}) }, body: raw ? b : b && JSON.stringify(b) }); const tx = await r.text(); let body; try { body = JSON.parse(tx); } catch { body = tx; } return { status: r.status, body }; };
  const mk = async n => { await call('POST', '/api/auth/register', { username: n, password: 'password123' }); return (await call('POST', '/api/auth/login', { username: n, password: 'password123' })).body.token; };
  const a = await mk('alice'), b = await mk('bob');
  const ws = (await call('POST', '/api/workspaces', { name: 'A', key: 'ACME' }, a)).body;
  assert.equal((await call('POST', `/api/workspaces/${ws.id}/members`, { username: 'bob', role: 'member' }, a)).status, 201);
  const pr = (await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'W', key: 'WEB' }, a)).body;
  const bobId = (await call('GET', '/api/auth/me', null, b)).body.id;
  const i1 = (await call('POST', `/api/projects/${pr.id}/issues`, { type: 'bug', title: 'Crash', storyPoints: 5, assigneeId: bobId, labels: ['x'] }, a)).body;
  const i2 = (await call('POST', `/api/projects/${pr.id}/issues`, { type: 'task', title: 'Fix', storyPoints: 3 }, a)).body;
  assert.equal(i1.status, 'Todo');
  await call('POST', `/api/issues/${i2.key}/links`, { type: 'blocks', target: i1.key }, a);
  assert.equal((await call('PATCH', `/api/issues/${i1.key}`, { status: 'Done' }, a)).body.error, 'blocked');
  const sp = (await call('POST', `/api/projects/${pr.id}/sprints`, { name: 'S1' }, a)).body;
  await call('PATCH', `/api/issues/${i1.key}`, { sprintId: sp.id }, a);
  await call('POST', `/api/sprints/${sp.id}/start`, {}, a);
  t0 = new Date('2026-01-02T10:00:00Z');
  await call('PATCH', `/api/issues/${i2.key}`, { status: 'Done' }, a);
  assert.equal((await call('PATCH', `/api/issues/${i1.key}`, { status: 'Done' }, b)).status, 200);
  const rep = (await call('GET', `/api/sprints/${sp.id}/report`, null, a)).body;
  assert.equal(rep.committedPoints, 5); assert.equal(rep.completedPoints, 5); assert.equal(rep.burndown.length, 2);
  assert.deepEqual(rep.burndown.map(x => x.remainingPoints), [5, 0]);
  const n = (await call('GET', '/api/notifications?unread=true', null, a)).body; assert.ok(n.length >= 1);
  const s = (await call('GET', '/api/search?q=' + encodeURIComponent('type:bug is:resolved -label:zz crash'), null, a)).body; assert.equal(s.length, 1);
  assert.equal((await call('GET', '/api/search?q=' + encodeURIComponent('status:"oops'), null, a)).status, 400);
  const csv = (await call('GET', `/api/projects/${pr.id}/export.csv`, null, a)).body; assert.ok(csv.startsWith('key,type,title'));
  const imp = (await call('POST', `/api/projects/${pr.id}/import.csv`, 'key,type,title,status\r\n,task,"a, b",Todo\r\n,bogus,x,Todo\r\n', a, true)).body;
  assert.equal(imp.created, 1); assert.equal(imp.errors[0].line, 3);
  const got = []; const rcv = http.createServer((q, r) => { let d = ''; q.on('data', c => d += c); q.on('end', () => { got.push([q.headers['x-pm-signature'], d]); r.end('ok'); }); }); await new Promise(r => rcv.listen(0, r));
  const h = (await call('POST', `/api/projects/${pr.id}/webhooks`, { url: `http://127.0.0.1:${rcv.address().port}/`, events: ['issue.created'], secret: 's' }, a)).body;
  await call('POST', `/api/projects/${pr.id}/issues`, { title: 'hook' }, a);
  await new Promise(r => setTimeout(r, 300));
  assert.equal(got.length, 1); assert.match(got[0][0], /^sha256=/);
  assert.equal((await call('GET', `/api/webhooks/${h.id}/deliveries`, null, a)).body[0].status, 'success');
  assert.equal((await call('GET', `/api/workspaces/${ws.id}/audit`, null, a)).status, 200);
  rcv.close(); srv.close();
});
