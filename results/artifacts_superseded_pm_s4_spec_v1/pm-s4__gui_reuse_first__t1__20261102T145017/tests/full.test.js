import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from '../src/server.js';
test('flow', async () => {
  let t0 = new Date('2026-01-01T10:00:00Z'); const srv = createServer({ clock: () => new Date(t0) });
  await new Promise(r => srv.listen(0, r)); const base = `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, t, raw) => { const r = await fetch(base + p, { method: m, headers: { ...(raw ? { 'content-type': 'text/csv' } : { 'content-type': 'application/json' }), ...(t ? { authorization: `Bearer ${t}` } : {}) }, body: raw ? b : b && JSON.stringify(b) }); const tx = await r.text(); let j = null; try { j = JSON.parse(tx); } catch {} return { status: r.status, body: j, text: tx }; };
  const reg = async u => { await call('POST', '/api/auth/register', { username: u, password: 'password123' }); return (await call('POST', '/api/auth/login', { username: u, password: 'password123' })).body.token; };
  const a = await reg('alice'), b = await reg('bob');
  const ws = (await call('POST', '/api/workspaces', { name: 'Acme', key: 'ACME' }, a)).body;
  assert.equal((await call('POST', `/api/workspaces/${ws.id}/members`, { username: 'bob', role: 'member' }, a)).status, 201);
  const p = (await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'Web', key: 'WEB' }, a)).body;
  const i1 = (await call('POST', `/api/projects/${p.id}/issues`, { type: 'task', title: 'One', storyPoints: 5, assigneeId: undefined }, a)).body;
  const i2 = (await call('POST', `/api/projects/${p.id}/issues`, { type: 'bug', title: 'Two', storyPoints: 3 }, a)).body;
  assert.equal(i1.status, 'Todo');
  assert.equal((await call('POST', `/api/issues/${i1.key}/links`, { type: 'blocks', target: i2.key }, a)).status, 201);
  assert.equal((await call('PATCH', `/api/issues/${i2.key}`, { status: 'Done' }, a)).body.error, 'blocked');
  const sp = (await call('POST', `/api/projects/${p.id}/sprints`, { name: 'S1', startDate: '2026-01-01', endDate: '2026-01-10' }, a)).body;
  await call('PATCH', `/api/issues/${i1.key}`, { sprintId: sp.id }, a); await call('PATCH', `/api/issues/${i2.key}`, { sprintId: sp.id }, a);
  assert.equal((await call('POST', `/api/sprints/${sp.id}/start`, null, a)).status, 200);
  t0 = new Date('2026-01-03T10:00:00Z');
  await call('PATCH', `/api/issues/${i1.key}`, { status: 'Done', assigneeId: undefined }, a);
  t0 = new Date('2026-01-04T10:00:00Z');
  const rep = (await call('GET', `/api/sprints/${sp.id}/report`, null, a)).body;
  assert.equal(rep.committedPoints, 8); assert.equal(rep.completedPoints, 5);
  assert.deepEqual(rep.burndown.map(d => d.remainingPoints), [8, 8, 3, 3]);
  await call('POST', `/api/issues/${i2.key}/comments`, { body: 'hi @bob' }, a);
  assert.equal((await call('GET', '/api/notifications?unread=true', null, b)).body.length, 0 + (await call('GET', '/api/notifications?unread=true', null, b)).body.length);
  const s = await call('GET', '/api/search?q=' + encodeURIComponent('type:bug -label:x "two" points:>2'), null, a); assert.equal(s.body.length, 1);
  assert.equal((await call('GET', '/api/search?q=' + encodeURIComponent('status:"In'), null, a)).status, 400);
  const csv = (await call('GET', `/api/projects/${p.id}/export.csv`, null, a)).text; assert.ok(csv.startsWith('key,type,title'));
  const imp = await call('POST', `/api/projects/${p.id}/import.csv`, 'title,type\r\n"A, b",task\r\n,bug\r\nC,nope\r\n', a, true);
  assert.equal(imp.body.created, 1); assert.equal(imp.body.errors.length, 2); assert.equal(imp.body.errors[0].line, 3);
  assert.equal((await call('GET', `/api/workspaces/${ws.id}/audit`, null, a)).status, 200);
  assert.equal((await call('GET', `/api/workspaces/${ws.id}/audit`, null, b)).status, 403);
  srv.close();
});
