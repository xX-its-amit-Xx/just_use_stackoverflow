import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from '../src/server.js';
test('full flow', async () => {
  let t = new Date('2026-01-01T10:00:00Z');
  const srv = createServer({ clock: () => t }); await new Promise(r => srv.listen(0, r)); const base = `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, tk) => { const r = await fetch(base + p, { method: m, headers: { 'content-type': 'application/json', ...(tk ? { authorization: `Bearer ${tk}` } : {}) }, body: b && JSON.stringify(b) }); const x = await r.text(); let j; try { j = JSON.parse(x); } catch { j = x; } return { status: r.status, body: j }; };
  await call('POST', '/api/auth/register', { username: 'alice', password: 'password123' });
  await call('POST', '/api/auth/register', { username: 'bob', password: 'password123' });
  const a = (await call('POST', '/api/auth/login', { username: 'alice', password: 'password123' })).body.token;
  const b = (await call('POST', '/api/auth/login', { username: 'bob', password: 'password123' })).body.token;
  const ws = (await call('POST', '/api/workspaces', { name: 'Acme', key: 'ACME' }, a)).body;
  await call('POST', `/api/workspaces/${ws.id}/members`, { username: 'bob', role: 'member' }, a);
  const pr = (await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'Web', key: 'WEB' }, a)).body;
  const sp = (await call('POST', `/api/projects/${pr.id}/sprints`, { name: 'S1', endDate: '2026-01-05' }, a)).body;
  const i1 = (await call('POST', `/api/projects/${pr.id}/issues`, { type: 'bug', title: 'Crash', storyPoints: 5, sprintId: sp.id, assigneeId: undefined, labels: ['x'] }, a)).body;
  const i2 = (await call('POST', `/api/projects/${pr.id}/issues`, { type: 'task', title: 'Other', storyPoints: 3, sprintId: sp.id }, a)).body;
  assert.equal(i2.key, 'WEB-2');
  assert.equal((await call('POST', `/api/sprints/${sp.id}/start`, {}, a)).status, 200);
  assert.equal((await call('POST', `/api/issues/WEB-1/links`, { type: 'blocks', target: 'WEB-2' }, a)).status, 201);
  assert.equal((await call('PATCH', `/api/issues/WEB-2`, { status: 'Done' }, a)).body.error, 'blocked');
  t = new Date('2026-01-02T10:00:00Z');
  await call('PATCH', `/api/issues/WEB-1`, { status: 'In Progress' }, a);
  assert.equal((await call('PATCH', `/api/issues/WEB-1`, { status: 'Done' }, a)).body.resolvedAt, '2026-01-02T10:00:00.000Z');
  assert.equal((await call('PATCH', `/api/issues/WEB-2`, { status: 'Done' }, a)).status, 200);
  const rep = (await call('GET', `/api/sprints/${sp.id}/report`, null, a)).body;
  assert.equal(rep.committedPoints, 8); assert.equal(rep.completedPoints, 8);
  assert.deepEqual(rep.burndown.map(x => x.remainingPoints), [8, 0]);
  await call('POST', `/api/issues/WEB-1/comments`, { body: 'hi @bob' }, a);
  assert.equal((await call('GET', '/api/notifications?unread=true', null, b)).body.length, 1);
  const s = await call('GET', '/api/search?q=' + encodeURIComponent('type:bug -label:y is:resolved crash'), null, a);
  assert.equal(s.body.length, 1);
  assert.equal((await call('GET', '/api/search?q=' + encodeURIComponent('foo:bar'), null, a)).status, 400);
  const csv = (await call('GET', `/api/projects/${pr.id}/export.csv`, null, a)).body;
  assert.ok(csv.startsWith('key,type,title'));
  const imp = await fetch(base + `/api/projects/${pr.id}/import.csv`, { method: 'POST', headers: { 'content-type': 'text/csv', authorization: 'Bearer ' + a }, body: 'key,type,title,status\r\n,task,"A, b",Todo\r\n,bad,x,Todo\r\n' });
  const ij = await imp.json(); assert.equal(ij.created, 1); assert.equal(ij.errors[0].line, 3);
  assert.equal((await call('GET', `/api/workspaces/${ws.id}/audit`, null, b)).status, 403);
  srv.close();
});
