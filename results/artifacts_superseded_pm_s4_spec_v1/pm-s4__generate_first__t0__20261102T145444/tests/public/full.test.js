import { test } from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import crypto from 'node:crypto';
import { createServer } from '../../src/server.js';

let t0 = new Date('2024-03-01T10:00:00Z');
async function setup() {
  const srv = createServer({ clock: () => t0 }); await new Promise(r => srv.listen(0, r));
  const base = `http://127.0.0.1:${srv.address().port}`;
  const call = async (m, p, b, t, raw) => { const r = await fetch(base + p, { method: m, headers: { 'content-type': raw ? 'text/csv' : 'application/json', ...(t ? { authorization: `Bearer ${t}` } : {}) }, body: raw ? b : b && JSON.stringify(b) }); const txt = await r.text(); let body; try { body = JSON.parse(txt); } catch { body = txt; } return { status: r.status, body }; };
  const user = async (n) => { await call('POST', '/api/auth/register', { username: n, password: 'password123' }); return (await call('POST', '/api/auth/login', { username: n, password: 'password123' })).body.token; };
  return { srv, call, user };
}
test('flow', async () => {
  const { srv, call, user } = await setup();
  const a = await user('alice'), b = await user('bob'), g = await user('gina');
  const ws = (await call('POST', '/api/workspaces', { name: 'Acme', key: 'ACME' }, a)).body;
  await call('POST', `/api/workspaces/${ws.id}/members`, { username: 'bob', role: 'member' }, a);
  await call('POST', `/api/workspaces/${ws.id}/members`, { username: 'gina', role: 'guest' }, a);
  const pr = (await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'Web', key: 'WEB' }, a)).body;
  assert.equal((await call('GET', `/api/projects/${pr.id}`, null, g)).status, 404);
  assert.equal((await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'x', key: 'XX' }, g)).status, 403);
  const i1 = (await call('POST', `/api/projects/${pr.id}/issues`, { type: 'task', title: 'One', storyPoints: 3 }, a)).body;
  assert.equal(i1.status, 'Todo');
  const i2 = (await call('POST', `/api/projects/${pr.id}/issues`, { type: 'bug', title: 'Two', storyPoints: 2, labels: ['x'] }, a)).body;
  assert.equal(i2.key, 'WEB-2');
  await call('POST', `/api/issues/${i1.key}/links`, { type: 'blocks', target: i2.key }, a);
  assert.equal((await call('GET', `/api/issues/${i2.key}`, null, a)).body.links[0].type, 'blocked_by');
  const bl = await call('PATCH', `/api/issues/${i2.key}`, { status: 'Done' }, a);
  assert.equal(bl.status, 409); assert.equal(bl.body.error, 'blocked');
  const sp = (await call('POST', `/api/projects/${pr.id}/sprints`, { name: 'S1', startDate: '2024-03-01', endDate: '2024-03-14' }, a)).body;
  await call('PATCH', `/api/issues/${i1.key}`, { sprintId: sp.id }, a);
  await call('PATCH', `/api/issues/${i2.key}`, { sprintId: sp.id }, a);
  assert.equal((await call('POST', `/api/sprints/${sp.id}/start`, null, a)).status, 200);
  t0 = new Date('2024-03-02T10:00:00Z');
  assert.equal((await call('PATCH', `/api/issues/${i1.key}`, { status: 'Done' }, a)).body.resolvedAt, t0.toISOString());
  t0 = new Date('2024-03-03T10:00:00Z');
  const rep = (await call('GET', `/api/sprints/${sp.id}/report`, null, a)).body;
  assert.deepEqual(rep.burndown.map(x => x.remainingPoints), [5, 2, 2]);
  assert.equal(rep.committedPoints, 5);
  const done = (await call('POST', `/api/sprints/${sp.id}/complete`, { carryOverTo: 'backlog' }, a)).body;
  assert.equal(done.state, 'completed');
  await call('POST', `/api/issues/${i1.key}/comments`, { body: 'hey @bob look' }, a);
  const n = (await call('GET', '/api/notifications?unread=true', null, b)).body;
  assert.equal(n.length, 1); assert.equal(n[0].type, 'mention');
  const s = (await call('GET', '/api/search?q=' + encodeURIComponent('-label:x is:open type:bug'), null, a)).body;
  assert.equal(s.length, 0);
  assert.equal((await call('GET', '/api/search?q=' + encodeURIComponent('"abc'), null, a)).status, 400);
  assert.equal((await call('GET', '/api/search?q=' + encodeURIComponent('label:x One'), null, a)).status, 200);
  const csv = (await call('GET', `/api/projects/${pr.id}/export.csv`, null, a)).body;
  assert.ok(csv.startsWith('key,type,title'));
  const imp = (await call('POST', `/api/projects/${pr.id}/import.csv`, 'key,type,title,status\r\n,task,"A, b",Todo\r\n,wat,Bad,Todo\r\n', a, true)).body;
  assert.equal(imp.created, 1); assert.equal(imp.errors[0].line, 3);
  const wf = { statuses: [{ name: 'Open', category: 'unstarted' }, { name: 'Closed', category: 'completed' }], transitions: [['Open', 'Closed']] };
  assert.equal((await call('PUT', `/api/projects/${pr.id}/workflow`, wf, a)).status, 400);
  const w2 = await call('PUT', `/api/projects/${pr.id}/workflow`, { ...wf, remap: { Todo: 'Open', Done: 'Closed', Backlog: 'Open', 'In Progress': 'Open', 'In Review': 'Open' } }, a);
  assert.equal(w2.status, 200);
  assert.equal((await call('GET', `/api/projects/${pr.id}/stats`, null, a)).status, 200);
  assert.equal((await call('GET', `/api/workspaces/${ws.id}/audit`, null, a)).body.length > 0, true);
  assert.equal((await call('GET', `/api/workspaces/${ws.id}/audit`, null, b)).status, 403);
  const me = (await call('GET', '/api/auth/me', null, a)).body;
  assert.equal((await call('DELETE', `/api/workspaces/${ws.id}/members/${me.id}`, null, a)).status, 400);
  srv.close();
});
test('webhook signature + rate limit + api token', async () => {
  const { srv, call, user } = await setup();
  const got = [];
  const hook = http.createServer((req, res) => { let d = ''; req.on('data', c => d += c); req.on('end', () => { got.push({ sig: req.headers['x-pm-signature'], d }); res.end('ok'); }); });
  await new Promise(r => hook.listen(0, r));
  const a = await user('alice');
  const tk = (await call('POST', '/api/tokens', { name: 'ci' }, a)).body;
  const ws = (await call('POST', '/api/workspaces', { name: 'Acme', key: 'ACME' }, tk.token)).body;
  const pr = (await call('POST', `/api/workspaces/${ws.id}/projects`, { name: 'Web', key: 'WEB' }, a)).body;
  const wh = (await call('POST', `/api/projects/${pr.id}/webhooks`, { url: `http://127.0.0.1:${hook.address().port}/`, events: ['issue.created'], secret: 's3' }, a)).body;
  await call('POST', `/api/projects/${pr.id}/issues`, { title: 'x' }, a);
  await new Promise(r => setTimeout(r, 300));
  assert.equal(got.length, 1);
  assert.equal(got[0].sig, 'sha256=' + crypto.createHmac('sha256', 's3').update(got[0].d).digest('hex'));
  assert.equal((await call('GET', `/api/webhooks/${wh.id}/deliveries`, null, a)).body[0].status, 'success');
  for (let i = 0; i < 5; i++) await call('POST', '/api/auth/login', { username: 'alice', password: 'wrongwrong' });
  assert.equal((await call('POST', '/api/auth/login', { username: 'alice', password: 'password123' })).status, 429);
  hook.close(); srv.close();
});
